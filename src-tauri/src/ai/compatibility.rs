use super::types::{ModelConfig, Protocol, Service};
use rig::completion::{CompletionRequest, Effort, Reasoning};
use serde_json::{json, Value};

pub fn model_spec(profile: &str, model_id: &str) -> Option<&'static rig::catalog::ModelSpec> {
    if ![
        "openai",
        "anthropic",
        "deepseek",
        "moonshot",
        "zai",
        "openrouter",
    ]
    .contains(&profile)
    {
        return None;
    }
    let provider = rig::providers::registry::ProviderId::resolve(profile).ok()?;
    rig::catalog::Catalog::builtin()
        .get(provider, model_id)
        .map(|resolved| resolved.spec)
}

pub const ADAPTERS: &[&str] = &[
    "generic",
    "openai",
    "anthropic",
    "deepseek",
    "qwen",
    "siliconflow",
    "vllm",
    "moonshot",
    "zai",
    "openrouter",
    "custom",
    "legacy_deepseek",
    "legacy_openai",
    "legacy_qwen",
];

pub fn adapter<'a>(service: &'a Service, model: &'a ModelConfig) -> &'a str {
    if let Some(value) = model.adapter_override.as_deref().filter(|s| !s.is_empty()) {
        return value;
    }
    if service.protocol == Protocol::AnthropicMessages {
        return if service.adapter == "custom" {
            "custom"
        } else {
            "anthropic"
        };
    }
    // Configurations from the first release explicitly selected a wire format.
    // Preserve it without guessing a provider from a display name or model alias.
    match model.thinking_format.as_str() {
        "deepseek" => "legacy_deepseek",
        "openai" => "legacy_openai",
        "qwen" => "legacy_qwen",
        _ => &service.adapter,
    }
}

pub fn validate_params(value: &Value) -> Result<(), String> {
    let Some(object) = value.as_object() else {
        return Err("自定义思考参数必须是 JSON 对象".into());
    };
    if object.is_empty() || value.to_string().len() > 4096 {
        return Err("自定义思考参数不能为空，且不能超过 4 KiB".into());
    }
    // Body-only extension. Never permit overriding identity, messages, credentials,
    // execution controls or the transport. Nested deployment-specific flags are OK.
    const RESERVED: &[&str] = &[
        "model",
        "messages",
        "system",
        "prompt",
        "stream",
        "stream_options",
        "max_tokens",
        "max_completion_tokens",
        "max_output_tokens",
        "api_key",
        "authorization",
        "headers",
        "base_url",
        "url",
        "tools",
        "tool_choice",
        "functions",
        "function_call",
    ];
    fn check(value: &Value, depth: usize) -> bool {
        if depth > 8 {
            return false;
        }
        match value {
            Value::Object(o) => o.iter().all(|(k, v)| {
                !RESERVED.contains(&k.to_ascii_lowercase().as_str())
                    && !["__proto__", "constructor", "prototype"].contains(&k.as_str())
                    && check(v, depth + 1)
            }),
            Value::Array(a) => a.iter().all(|v| check(v, depth + 1)),
            _ => true,
        }
    }
    if !check(value, 0) {
        return Err("自定义参数包含保留字段或嵌套过深".into());
    }
    Ok(())
}

pub fn parameters(model: &ModelConfig, service: &Service) -> Value {
    if model.thinking_mode == "default" {
        return json!({});
    }
    let enabled = model.thinking_mode == "enabled";
    match adapter(service, model) {
        "custom" => if enabled {
            model.thinking_on_params.clone()
        } else {
            model.thinking_off_params.clone()
        }
        .unwrap_or(json!({})),
        "qwen" | "siliconflow" | "legacy_qwen" => json!({"enable_thinking":enabled}),
        "vllm" => json!({"chat_template_kwargs":{"enable_thinking":enabled}}),
        "legacy_deepseek" => json!({"thinking":{"type":if enabled {"enabled"} else {"disabled"}}}),
        "legacy_openai" => {
            json!({"reasoning_effort":if enabled {model.reasoning_effort.as_deref().unwrap_or("high")} else {"none"}})
        }
        // The remaining formats are generated by Rig, not this extension map.
        _ => json!({}),
    }
}

pub fn configure(
    mut request: CompletionRequest,
    model: &ModelConfig,
    service: &Service,
) -> Result<CompletionRequest, String> {
    if model.thinking_mode == "default" {
        return Ok(request);
    }
    let profile = adapter(service, model);
    let enabled = model.thinking_mode == "enabled";
    let support = if model.capabilities.thinking == "unknown" {
        &model.reported_capabilities.thinking
    } else {
        &model.capabilities.thinking
    };
    if support == "unsupported" {
        return Err("此模型不支持思考控制，请选择跟随服务或修改能力配置".into());
    }
    match profile {
        "generic" => return Err("请在高级兼容设置中选择此接口的适配类型，再开启或关闭思考".into()),
        "custom" => {
            let value = if enabled {
                &model.thinking_on_params
            } else {
                &model.thinking_off_params
            };
            validate_params(value.as_ref().ok_or("请配置当前思考开关对应的自定义参数")?)?;
        }
        "qwen" | "siliconflow" | "vllm" | "legacy_deepseek" | "legacy_qwen" | "legacy_openai" => {}
        "zai" if enabled && model.model_id.starts_with("glm-4") => {
            return Ok(request.additional_params(json!({"thinking":{"type":"enabled"}})));
        }
        _ => {
            let budget_mode = profile == "anthropic"
                && model_spec(profile, &model.model_id)
                    .is_none_or(|s| s.reasoning.budget().is_some());
            let reasoning = if !enabled {
                Reasoning::Off
            } else if budget_mode {
                Reasoning::Budget {
                    tokens: model.reasoning_budget.unwrap_or_else(|| {
                        model_spec(profile, &model.model_id)
                            .and_then(|s| s.reasoning.budget())
                            .map_or(1024, |b| *b.start())
                    }),
                }
            } else {
                let default = model_spec(profile, &model.model_id)
                    .and_then(|s| s.reasoning.default_effort())
                    .map(|e| e.as_str())
                    .unwrap_or("high");
                let effort = match model.reasoning_effort.as_deref().unwrap_or(default) {
                    "minimal" => Effort::Minimal,
                    "low" => Effort::Low,
                    "medium" => Effort::Medium,
                    "high" => Effort::High,
                    "xhigh" => Effort::XHigh,
                    "max" => Effort::Max,
                    _ => return Err("思考强度无效".into()),
                };
                Reasoning::Effort(effort)
            };
            request = request.reasoning(reasoning);
        }
    }
    if let Some(spec) = model_spec(profile, &model.model_id) {
        spec.validate(&request.options)
            .map_err(|_| "所选思考强度、预算或开关不受该模型支持，请调整配置")?;
    }
    Ok(request.additional_params(parameters(model, service)))
}

// Logs allow only controlled scalar parameters. Arbitrary custom JSON is never logged.
pub fn log_parameters(model: &ModelConfig, service: &Service) -> Value {
    let profile = adapter(service, model);
    let reasoning = configure(CompletionRequest::new("log-options"), model, service)
        .ok()
        .and_then(|r| r.options.reasoning);
    json!({"maxOutputTokens":model.max_output_tokens,"thinkingMode":model.thinking_mode,
        "adapter":profile,"reasoning":reasoning,
        "requestOptions":if profile == "custom" { json!({"custom":true}) } else { parameters(model,service) }})
}
